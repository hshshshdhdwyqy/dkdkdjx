def detail_text(label):
    """متن HTML صفحه‌ی توضیح؛ None اگه برای این دکمه توضیحی نیست."""
    d = DETAILS.get(label)
    if not d:
        return None
    title, rows, note = d
    out = [f"<b>{html.escape(title)}</b>\n"]
    for cmd, desc in rows:
        out.append(f"<blockquote><code>{html.escape(cmd)}</code>\n<b>{html.escape(desc)}</b></blockquote>")
    if note:
        out.append(f"\n<b>نکته:</b> {html.escape(note)}")
    return "\n".join(out)
